"""
Analysis result schema definitions.

Defines data structures for MEDDIC analysis and coaching insights.
"""

from datetime import datetime
from enum import Enum
from typing import Optional
from pydantic import BaseModel, Field


class RatingLevel(str, Enum):
    """Rating scale for MEDDIC dimensions."""
    STRONG = "strong"
    MODERATE = "moderate"
    WEAK = "weak"
    NOT_DISCUSSED = "not_discussed"


class MEDDICDimension(BaseModel):
    """Individual MEDDIC dimension assessment."""
    rating: RatingLevel = RatingLevel.NOT_DISCUSSED
    score: int = Field(default=0, ge=0, le=100)
    evidence: list[str] = Field(default_factory=list)  # Quotes from transcript
    notes: Optional[str] = None


class MEDDICScore(BaseModel):
    """
    MEDDIC qualification framework scores.

    M - Metrics: Quantifiable measures of success
    E - Economic Buyer: Person with budget authority
    D - Decision Criteria: Formal evaluation criteria
    D - Decision Process: Steps to make a decision
    I - Identify Pain: Business problems to solve
    C - Champion: Internal advocate
    """
    metrics: MEDDICDimension = Field(default_factory=MEDDICDimension)
    economic_buyer: MEDDICDimension = Field(default_factory=MEDDICDimension)
    decision_criteria: MEDDICDimension = Field(default_factory=MEDDICDimension)
    decision_process: MEDDICDimension = Field(default_factory=MEDDICDimension)
    identify_pain: MEDDICDimension = Field(default_factory=MEDDICDimension)
    champion: MEDDICDimension = Field(default_factory=MEDDICDimension)

    # Overall
    total_score: int = Field(default=0, ge=0, le=100)
    qualification_status: str = "unqualified"  # unqualified, partially_qualified, qualified


class CoachingInsight(BaseModel):
    """A specific coaching recommendation for the sales rep."""
    category: str  # e.g., "objection_handling", "discovery", "closing"
    priority: str = "medium"  # high, medium, low
    observation: str  # What was observed
    recommendation: str  # What to do differently
    example_phrase: Optional[str] = None  # Suggested language


class BuyerSignal(BaseModel):
    """Detected buyer signal from conversation."""
    signal_type: str  # "positive", "negative", "neutral"
    category: str  # "budget", "timeline", "competition", "objection"
    description: str
    quote: Optional[str] = None  # Actual quote from transcript
    timestamp: Optional[float] = None  # When in conversation


class NextStep(BaseModel):
    """Recommended next action."""
    action: str
    owner: str = "sales_rep"  # sales_rep, customer, internal
    due_date: Optional[str] = None
    priority: str = "medium"


class AnalysisResult(BaseModel):
    """
    Complete analysis output for a conversation.

    Generated by modules/03-sales-conversation/
    Aggregates outputs from all analysis agents.
    """
    id: str = Field(..., description="Unique analysis identifier")
    conversation_id: str

    # Agent outputs
    meddic: MEDDICScore = Field(default_factory=MEDDICScore)
    coaching_insights: list[CoachingInsight] = Field(default_factory=list)
    buyer_signals: list[BuyerSignal] = Field(default_factory=list)

    # Summaries
    executive_summary: Optional[str] = None
    customer_summary: Optional[str] = None  # Customer-facing summary
    internal_notes: Optional[str] = None

    # Next steps
    next_steps: list[NextStep] = Field(default_factory=list)
    follow_up_date: Optional[str] = None

    # Key entities extracted
    competitors_mentioned: list[str] = Field(default_factory=list)
    products_discussed: list[str] = Field(default_factory=list)
    objections_raised: list[str] = Field(default_factory=list)

    # CRM data for Salesforce sync
    crm_fields: dict = Field(default_factory=dict)

    # Processing metadata
    model_used: str = "gemini-2.0-flash"
    processing_time_seconds: Optional[float] = None
    token_usage: Optional[dict] = None
    analyzed_at: datetime = Field(default_factory=datetime.utcnow)

    # Quality
    confidence_score: Optional[float] = None

    class Config:
        json_schema_extra = {
            "example": {
                "id": "analysis_20250108_001",
                "conversation_id": "case_20250108_001",
                "meddic": {
                    "total_score": 72,
                    "qualification_status": "partially_qualified"
                },
                "executive_summary": "Productive demo call with clear interest...",
            }
        }
